/// Hot — 256-entry sequential colormap (black -> red -> yellow -> white).
pub fn hot() -> Vec<[f64; 4]> {
    let mut colors = Vec::with_capacity(256);
    for i in 0..256 {
        let t = i as f64 / 255.0;
        let r = (t * 3.0).min(1.0);
        let g = ((t - 1.0 / 3.0) * 3.0).clamp(0.0, 1.0);
        let b = ((t - 2.0 / 3.0) * 3.0).clamp(0.0, 1.0);
        colors.push([r, g, b, 1.0]);
    }
    colors
}

/// Cool — 256-entry diverging colormap (cyan -> magenta).
pub fn cool() -> Vec<[f64; 4]> {
    let mut colors = Vec::with_capacity(256);
    for i in 0..256 {
        let t = i as f64 / 255.0;
        colors.push([t, 1.0 - t, 1.0, 1.0]);
    }
    colors
}

/// Spring — 256-entry colormap (magenta -> yellow).
pub fn spring() -> Vec<[f64; 4]> {
    let mut colors = Vec::with_capacity(256);
    for i in 0..256 {
        let t = i as f64 / 255.0;
        colors.push([1.0, t, 1.0 - t, 1.0]);
    }
    colors
}

