/// Linearly interpolate between control points to produce `n` RGBA entries.
///
/// `control_points` is a slice of `(t, R, G, B)` tuples sorted by `t` in `[0, 1]`.
fn interpolate_control_points(control_points: &[(f64, f64, f64, f64)], n: usize) -> Vec<[f64; 4]> {
    let mut colors = Vec::with_capacity(n);

    for i in 0..n {
        let t = i as f64 / (n - 1) as f64;

        // Find the two control points that bracket `t`.
        let mut lo = 0;
        for j in 0..control_points.len() - 1 {
            if control_points[j + 1].0 >= t {
                lo = j;
                break;
            }
            lo = j;
        }
        let hi = (lo + 1).min(control_points.len() - 1);

        let (t0, r0, g0, b0) = control_points[lo];
        let (t1, r1, g1, b1) = control_points[hi];

        let frac = if (t1 - t0).abs() < 1e-12 {
            0.0
        } else {
            (t - t0) / (t1 - t0)
        };

        let r = r0 + (r1 - r0) * frac;
        let g = g0 + (g1 - g0) * frac;
        let b = b0 + (b1 - b0) * frac;

        colors.push([r, g, b, 1.0]);
    }

    colors
}
