/// Jet — 256-entry rainbow colormap.
pub fn jet() -> Vec<[f64; 4]> {
    let mut colors = Vec::with_capacity(256);
    for i in 0..256 {
        let t = i as f64 / 255.0;
        let r = if t < 0.375 {
            0.0
        } else if t < 0.625 {
            (t - 0.375) / 0.25
        } else if t < 0.875 {
            1.0
        } else {
            1.0 - (t - 0.875) / 0.125
        }
        .clamp(0.0, 1.0);

        let g = if t < 0.125 {
            0.0
        } else if t < 0.375 {
            (t - 0.125) / 0.25
        } else if t < 0.625 {
            1.0
        } else if t < 0.875 {
            1.0 - (t - 0.625) / 0.25
        } else {
            0.0
        }
        .clamp(0.0, 1.0);

        let b = if t < 0.125 {
            0.5 + t / 0.125 * 0.5
        } else if t < 0.375 {
            1.0
        } else if t < 0.625 {
            1.0 - (t - 0.375) / 0.25
        } else {
            0.0
        }
        .clamp(0.0, 1.0);

        colors.push([r, g, b, 1.0]);
    }
    colors
}

