/// Built-in color palette data.
///
/// Each function returns a `Vec<[f64; 4]>` of RGBA colors in `[0.0, 1.0]`.
/// Continuous colormaps have 256 entries; categorical colormaps have one entry per category.

/// Helper to convert `(R, G, B)` tuples (0.0-1.0) into `[R, G, B, 1.0]` arrays.
fn rgb_to_rgba(data: &[(f64, f64, f64)]) -> Vec<[f64; 4]> {
    data.iter().map(|&(r, g, b)| [r, g, b, 1.0]).collect()
}

